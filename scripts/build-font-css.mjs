/**
 * Generates src/fonts.css from the @fontsource packages, keeping only the woff2 sources.
 *
 * @fontsource ships each @font-face with both a woff2 and a woff URL. Every browser we
 * support reads woff2, so the woff URLs are dead weight — but they still cost real bytes in
 * the render-blocking CSS bundle (these fonts are split into ~124 unicode-range subsets each,
 * so the duplicated URLs add up fast). Stripping them roughly halves the font CSS and stops
 * the unused .woff files from being copied into the build output.
 *
 * Run via `npm run build:fonts` after changing which fonts/weights the app uses.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

/** Weights the app actually renders — see --font-sans / --font-gothic in index.css. */
const SOURCES = [
  { pkg: '@fontsource/klee-one', css: '400.css' },
  { pkg: '@fontsource/klee-one', css: '600.css' },
  { pkg: '@fontsource/zen-maru-gothic', css: '700.css' },
];

let out = `/* Generated by scripts/build-font-css.mjs — do not edit by hand. */\n`;

for (const { pkg, css } of SOURCES) {
  const source = readFileSync(resolve(root, 'node_modules', pkg, css), 'utf8');

  const rewritten = source
    // Drop the woff fallback, keeping only the woff2 source.
    .replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/g, '')
    // Point ./files/... at the package inside node_modules, relative to src/fonts.css.
    .replace(/url\(\.\/files\//g, `url(../node_modules/${pkg}/files/`)
    // swap always shows fallback text immediately, then re-renders once the matching
    // unicode-range subset arrives — for dynamically generated text (this app draws
    // random kanji from a pool), that means individual characters visibly pop from a
    // system-font weight to the webfont's weight at random moments after first paint.
    // optional makes the browser use the webfont only if it's already available (e.g.
    // cached from an earlier draw in this session); otherwise it commits to the
    // fallback for that paint instead of swapping mid-render, trading "always ends up
    // in the exact right font" for "never visibly flickers".
    .replace(/font-display:\s*swap;/g, 'font-display: optional;');

  out += `\n${rewritten}`;
}

const target = resolve(root, 'src/fonts.css');
writeFileSync(target, out);

const faces = (out.match(/@font-face/g) ?? []).length;
console.log(`src/fonts.css を生成しました（@font-face ${faces}件, ${(out.length / 1024).toFixed(0)}KB）`);
